export function nextTaskId(tasks: Task[]): string {
  const max = tasks.reduce((acc, task) => {
    const n = Number(task.id.replace("TSK-", ""));
    return Number.isFinite(n) ? Math.max(acc, n) : acc;
  }, 100);
  return `TSK-${max + 1}`;
}
